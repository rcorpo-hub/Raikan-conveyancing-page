test('callback team email includes styled website template and no reference number', () => {
  const email = buildCallbackTeamEmail({ name: 'Jane Doe', phone: '0412345678', time: 'Morning' });
  assert.equal(email.subject, 'Callback requested');
  assert(email.text.includes('Jane Doe'));
  assert(email.text.includes('0412345678'));
  assert(email.text.includes('Morning'));
  assert(!email.text.includes('Reference'));
  assert(email.html.includes('Callback Requested'));
  assert(email.html.includes('Jane Doe'));
  assert(!email.html.includes('Reference'));
});
